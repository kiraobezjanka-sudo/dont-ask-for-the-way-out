export function validateDialogue() {
  const errors = [];
  for (const [nodeId, node] of Object.entries(dialogue)) {
    if (!node.choices?.length) errors.push(`${nodeId}: нет вариантов`);
    for (const choice of node.choices ?? []) {
      if (choice.next && !dialogue[choice.next]) errors.push(`${nodeId}/${choice.id}: нет узла ${choice.next}`);
      if (choice.ending && !endings[choice.ending]) errors.push(`${nodeId}/${choice.id}: нет концовки ${choice.ending}`);
    }
  }
  return errors;
}
